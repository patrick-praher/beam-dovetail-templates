/**
 * Generates ready-to-print template sets for common joist sizes, e.g. for
 * publishing on a model platform. Usage: npm run presets
 */
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { computeJoint } from '../src/core/joint';
import { initKernel } from '../src/core/kernel';
import { DEFAULTS, type Params } from '../src/core/params';
import { buildModel, type TemplateModel } from '../src/core/shapes';
import { meshToStl } from '../src/export/stl';

const OUT = 'makerworld';
const BED = 256;

/** Joist width × height in mm. */
const JOISTS: [number, number][] = [
  [60, 120], [60, 160], [80, 160], [80, 200], [100, 200], [100, 240], [120, 240],
];

/** Router setup shared by all sets; the app covers every other combination. */
const ROUTER: Partial<Params> = {
  bitDiameter: 25.4,
  bitAngleDeg: 14,
  bitCutLength: 22,
  bushingDiameter: 30,
  bushingLength: 6,
  tenonLength: 20,
};

const size = (t: TemplateModel) => [t.bounds.x1 - t.bounds.x0, t.bounds.y1 - t.bounds.y0];
const fits = (t: TemplateModel) => Math.max(...size(t)) <= BED;
const f = (n: number) => n.toFixed(1);

const k = await initKernel();
rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const rows: string[] = [];
for (const [w, h] of JOISTS) {
  const base: Params = {
    ...DEFAULTS, ...ROUTER,
    joistWidth: w, joistHeight: h,
    beamWidth: Math.max(100, w + 20), beamHeight: h + 40,
    bedX: BED, bedY: BED,
  };
  // Prefer the support frame; drop it when the template would not fit the bed.
  let joint = computeJoint(base);
  if (!joint.ok) throw new Error(`${w}x${h}: ${joint.issues.find((i) => i.level === 'error')!.msg}`);
  let model = buildModel(k, joint);
  if (!fits(model.tenon)) {
    joint = computeJoint({ ...base, frame: false });
    model = buildModel(k, joint);
  }
  for (const t of [model.socket, model.tenon]) {
    if (!fits(t)) throw new Error(`${w}x${h}: ${t.name} template does not fit a ${BED} mm bed`);
  }
  for (const i of joint.issues) if (i.level === 'warn') console.warn(`${w}x${h}: ${i.msg}`);

  const dir = join(OUT, `joist-${w}x${h}`);
  mkdirSync(dir);
  for (const t of [model.socket, model.tenon]) {
    writeFileSync(join(dir, `dovetail-${t.name}-template-${w}x${h}.stl`), Buffer.from(meshToStl(t.printMesh)));
  }
  const p = joint.p;
  rows.push(
    `| ${w} × ${h} | ${joint.width} × ${joint.height} | ${size(model.socket).map((n) => n.toFixed(0)).join(' × ')} | ` +
      `${size(model.tenon).map((n) => n.toFixed(0)).join(' × ')}${p.frame ? '' : ' (no frame)'} | ` +
      `${f(p.templateThickness + joint.socketDepth)} | ${f(p.templateThickness + joint.tenonDepth)} |`,
  );
  console.log(`${w}x${h}: ok${p.frame ? '' : ' (tenon template without frame)'}`);
}

const d = { ...DEFAULTS, ...ROUTER } as Params;
writeFileSync(
  join(OUT, 'SETS.md'),
  `# Generated template sets

Generated by \`npm run presets\`. Do not edit; change \`scripts/generate-presets.ts\` instead.

All sets are for this router setup:

- dovetail bit Ø ${d.bitDiameter} mm, ${d.bitAngleDeg}° per side, at least ${d.tenonLength + d.depthGap} mm cutting length
- template guide (copy ring) Ø ${d.bushingDiameter} mm, collar shorter than ${d.templateThickness} mm
- tenon ${d.tenonLength} mm long, socket ${d.tenonLength + d.depthGap} mm deep, wedge taper ${d.taperDeg}° per side, flank clearance ${d.clearance} mm
- plate ${d.templateThickness} mm thick, stop lips ${d.lipDepth} mm, screw holes Ø ${d.screwDiameter} mm

Sizes in mm. "Bit depth" is measured below the router base.

| Joist | Dovetail (width at top × height) | Socket template | Tenon template | Bit depth socket | Bit depth tenon |
| --- | --- | --- | --- | --- | --- |
${rows.join('\n')}
`,
);
